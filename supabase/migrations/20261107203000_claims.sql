begin;
-- Read current server-managed roles, not possibly stale JWT metadata.
create or replace function public.claims_role() returns text
language sql stable security definer set search_path = '' as $$
  select u.raw_app_meta_data->>'hack_muc_role' from auth.users u
  where u.id = auth.uid() and u.email_confirmed_at is not null
    and coalesce(u.is_anonymous, false) = false
    and (u.invited_at is not null or u.raw_app_meta_data->>'hack_muc_access' = 'true')
    and (u.banned_until is null or u.banned_until < now());
$$;
revoke all on function public.claims_role() from public, anon;
grant execute on function public.claims_role() to authenticated;

create table public.claims (
  id uuid primary key default gen_random_uuid(),
  case_id text generated always as ('CLM-' || id::text) stored unique,
  submitted_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now(),
  case_status text not null default 'open' check (case_status in ('open', 'closed')),
  incident_date date not null,
  policy_reference text check (length(policy_reference) <= 120),
  claim_summary text not null check (length(btrim(claim_summary)) between 10 and 5000),
  claim_type text check (length(claim_type) between 1 and 100),
  repair_type text check (length(repair_type) between 1 and 100),
  quote_eur numeric(12,2) check (quote_eur >= 0),
  policy_active_on_incident boolean,
  incident_report_present boolean,
  itemized_quote_present boolean,
  injury_reported boolean,
  liability_disputed boolean,
  duplicate_flag boolean,
  evidence_conflict boolean
);
create index claims_owner_created_idx on public.claims(submitted_by, created_at desc);
create index claims_status_created_idx on public.claims(case_status, created_at desc);
alter table public.claims enable row level security;
revoke all on public.claims from anon, authenticated;
grant select on public.claims to authenticated;
-- Ownership, IDs, timestamps, status and internal review flags are generated by the database.
grant insert (incident_date, policy_reference, claim_summary, claim_type, repair_type, quote_eur,
  policy_active_on_incident, incident_report_present, itemized_quote_present, injury_reported, liability_disputed)
  on public.claims to authenticated;
create policy claims_read on public.claims for select to authenticated using (
  (public.claims_role() = 'claims_handler' and submitted_by = auth.uid())
  or public.claims_role() in ('reviewer', 'policy_manager', 'admin')
);
create policy claims_submit on public.claims for insert to authenticated with check (
  public.claims_role() in ('claims_handler', 'reviewer', 'admin')
  and submitted_by = auth.uid() and case_status = 'open'
  and incident_date <= current_date
  and duplicate_flag is null and evidence_conflict is null
);
comment on table public.claims is 'Submitted claim facts. Null means unknown; internal review flags require a future verified review workflow. No persisted verdict or payment approval.';
commit;
