// Compiles the Vercel Functions (TypeScript in src/policy-api/functions/) to plain JavaScript in api/.
// Why: Vercel's TypeScript compiler for functions needs `ts.sys`, which TypeScript 7 no longer has, so
// TS files in api/ cannot be deployed with this repo's TypeScript. The output is committed; a test
// (tests/api-bundle.test.ts) fails if it is stale. Packages stay external and are traced by Vercel.
import { build } from 'esbuild';

export const functions = ['policy', 'policy-ai', 'voice-session'];
export const options = name => ({
  entryPoints: [`src/policy-api/functions/${name}.ts`],
  outfile: `api/${name}.js`,
  bundle: true, packages: 'external', platform: 'node', format: 'esm', target: 'node22',
  legalComments: 'none', logLevel: 'warning',
  banner: { js: '// GENERATED by `npm run build:api` from src/policy-api/. Do not edit; edit the TypeScript sources instead.' },
});

if (import.meta.url === `file://${process.argv[1]}`) {
  for (const name of functions) await build(options(name));
  console.log(`api/: built ${functions.map(n => `${n}.js`).join(', ')}`);
}
